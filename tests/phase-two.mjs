import { chromium, expect } from '@playwright/test'

const browser = await chromium.launch()
const url = process.env.ALBUM_URL || 'http://127.0.0.1:5173/#album'
try {
 for (const [name, width, height] of [['phone', 390, 844], ['tablet', 800, 1280], ['landscape', 1280, 800]]) {
  const page = await browser.newPage({ viewport:{width,height}, hasTouch:true })
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.addInitScript(()=>{
   window.sceneSounds={tones:0,noises:0}
   for(const [method,key] of [['createOscillator','tones'],['createBufferSource','noises']]){
    const original=AudioContext.prototype[method]
    AudioContext.prototype[method]=function(...args){window.sceneSounds[key]++;return original.apply(this,args)}
   }
  })
  await page.goto(url)
  await page.getByRole('button',{name:'Abrir o álbum Bê e Mô'}).tap()
  const picker=page.getByRole('combobox',{name:'Ir para a página'})
  const active=page.locator('.page-display[data-page]:not([inert]):not([hidden])')
  async function go(n){
   await picker.selectOption(String(n))
   await expect(active).toHaveAttribute('data-page',String(n))
   await expect.poll(async()=>{
    const r=await active.boundingBox()
    return Math.abs(r.x+r.width/2-width/2)
   }).toBeLessThan(13)
  }
  const button=(name)=>page.getByRole('button',{name,exact:true})
  await button('Abrir a carta').tap()
  await expect(active.locator('.envelope-address')).toHaveText('Para meu amor')
  await expect.poll(()=>page.evaluate(()=>window.sceneSounds.noises)).toBeGreaterThanOrEqual(3)
  await go(3)
  await expect(active.locator('.fate-note')).toContainText('Nossas vidas sempre estiveram tão perto')
  await expect.poll(()=>page.evaluate(()=>window.sceneSounds.tones)).toBe(3)
  await go(4)
  await button('Devolver a cor ao mundo').tap()
  await expect(active.locator('.encounter-frame')).toHaveClass(/colorful/)
  await go(5)
  await expect(active.locator('.ticket-route')).toHaveText('24 horas')
  await go(7)
  await expect.poll(()=>page.evaluate(()=>window.sceneSounds.tones)).toBe(11)
  await expect(active.locator('.tower-clock-wall .tower-clock')).toBeVisible()
  const hand=active.locator('.hand-second')
  const transform=await hand.getAttribute('style')
  await expect(hand).not.toHaveAttribute('style',transform)
  await page.screenshot({path:`artifacts/phase2-${name}-tower.png`})
  await go(8)
  await expect(active.locator('.fairy-top i')).toHaveCount(7)
  await expect(active.locator('.fairy-bottom i')).toHaveCount(7)
  await active.locator('.polaroid-clickable').first().tap()
  await expect(page.locator('.lightbox-card figcaption')).toBeVisible()
  await button('Fechar foto').tap()
  await go(7)
  await expect.poll(()=>page.evaluate(()=>window.sceneSounds.tones)).toBe(19)
  await go(9)
  await button('Virar fotografia 8 para ler o recado').tap()
  await button('Ampliar tudo').tap()
  await expect(page.locator('.enlarged-memory-note')).toHaveText('Eu gosto de cuidar de você.')
  await expect(page.locator('.lightbox-card img')).toHaveCount(1)
  await button('Fechar foto').tap()
  await go(11)
  await button('Tirar fotos').tap()
  await expect(active.locator('.booth-stage')).toHaveClass(/booth-capturing/)
  await expect(active.locator('.booth-stage')).not.toHaveClass(/booth-open/)
  await expect.poll(()=>active.locator('.booth-exposure img').evaluate(img=>img.naturalWidth)).toBeGreaterThan(0)
  await expect(active.locator('.booth-exposure')).toHaveCSS('animation-iteration-count','3')
  await expect(button('Ampliar imagens')).toBeVisible()
  const strips=active.locator('.photo-strips .photostrip')
  await expect(strips).toHaveCount(2)
  await expect(active.locator('.photo-strips img')).toHaveCount(6)
  await expect.poll(()=>active.locator('.photo-strips').evaluate(root=>{
   const r=root.getBoundingClientRect()
   return Array.from(root.querySelectorAll('figure')).every(item=>{
    const f=item.getBoundingClientRect()
    return f.height>0&&f.top>=r.top-2&&f.bottom<=r.bottom+2&&f.left>=r.left-2&&f.right<=r.right+2
   })
  })).toBeTruthy()
  await page.screenshot({path:`artifacts/phase2-${name}-booth.png`})
  await button('Ampliar imagens').tap()
  await expect(page.locator('.enlarged-strips img')).toHaveCount(6)
  await button('Fechar foto').tap()
  await go(12)
  for(let i=0;i<3;i++){
   await button('Tirar fotografia').tap()
   await expect(active.locator('.instant-print')).toHaveCount(i+1)
  }
  await button('Reiniciar fotos').tap()
  await expect(active.locator('.instant-print')).toHaveCount(0)
  await go(14)
  const lamp=await active.locator('.lamp-shade').boundingBox()
  const room=await active.locator('.dark-room').boundingBox()
  const touch=await page.context().newCDPSession(page)
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:room.x+room.width*.24,y:room.y+room.height*.72}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:lamp.x+lamp.width/2,y:lamp.y+lamp.height/2}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(active.locator('.dark-room')).toHaveClass(/room-lit/)
  await go(15)
  await button('Fechar nosso cadeado').tap()
  await expect(active.locator('.river-picture')).toHaveClass(/lock-closed/)
  await expect(active.locator('.bridge-lock-post')).toBeVisible()
  await page.waitForTimeout(1900)
  await button('Ver outra vez').tap()
  await expect(active.locator('.river-picture')).not.toHaveClass(/lock-closed/)
  await go(16)
  await expect(active.locator('.rings-photo img')).toBeHidden()
  await button('Pegar a aliança').tap()
  await button('Mindinho').tap()
  await expect(active.locator('.ring-message')).toHaveText('Tente outro dedo.')
  const ring=await button('Pegar a aliança').boundingBox()
  const correct=await button('Anelar').boundingBox()
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:ring.x+ring.width/2,y:ring.y+ring.height/2}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:correct.x+correct.width/2,y:correct.y+correct.height/2}]})
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(active.locator('.rings-photo img')).toBeVisible()
  await active.locator('.rings-photo img').evaluate(img=>img.decode())
  await page.waitForTimeout(550)
  await page.screenshot({path:`artifacts/phase2-${name}-ring.png`})
  await go(18)
  await button('Ouvir nossa próxima melodia').tap()
  await expect(page.locator('audio')).toHaveJSProperty('paused',false)
  await go(7)
  await expect(page.locator('audio')).toHaveJSProperty('paused',false)
  expect(errors).toEqual([])
  console.log(name,'phase 2 passed',await page.evaluate(()=>window.sceneSounds))
  await page.close()
 }
} finally {
 await browser.close()
}
